// Bundles public/js/sim/*.js into server/src/sim.gen.js for the Cloudflare Worker.
// Workers cannot eval code, so the rule files are wrapped in a factory: every room calls createSim() for its own copy.
// Runs automatically before `wrangler dev` / `wrangler deploy` (see server/wrangler.toml).
import { existsSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
const dir = new URL('../public/js/sim/', import.meta.url);
const files = readdirSync(dir).filter(f => f.endsWith('.js')).sort();
const body = files.map(f => `/* ${f} */\n` + readFileSync(new URL(f, dir), 'utf8')).join('\n');
const out = `// GENERATED by tools/build-server.mjs from public/js/sim. Do not edit.\nexport function createSim(){\n${body}\nreturn {NET, over:()=>!!(G&&G.over)};\n}\n`;
const dest = new URL('../server/src/sim.gen.js', import.meta.url);
// unchanged output is not rewritten, so wrangler's file watcher does not loop
if (existsSync(dest) && readFileSync(dest, 'utf8') === out) console.log('server/src/sim.gen.js is up to date');
else { writeFileSync(dest, out); console.log('wrote server/src/sim.gen.js from', files.length, 'files'); }
